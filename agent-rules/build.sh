#!/usr/bin/env bash
# Generate each agent's global rules file from shared.md plus its own tail.
# A GitButler-managed block already present in a target is carried over.
set -euo pipefail

src="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
repo="$(dirname "$src")"

build() {
    local tool=$1 question_tool=$2 target="$repo/$3" block="" tmp
    if [ -f "$target" ]; then
        block=$(sed -n '/<!-- gitbutler-agent-setup:start -->/,/<!-- gitbutler-agent-setup:end -->/p' "$target")
    fi
    tmp=$(mktemp)
    {
        printf '<!-- Generated by agent-rules/build.sh. Edit agent-rules/shared.md or agent-rules/%s.md instead. -->\n\n' "$tool"
        sed "s/{{QUESTION_TOOL}}/$question_tool/" "$src/shared.md"
        printf '\n'
        cat "$src/$tool.md"
        if [ -n "$block" ]; then
            printf '\n%s\n' "$block"
        fi
    } >"$tmp"
    chmod 644 "$tmp"
    mv "$tmp" "$target"
    echo "wrote $3"
}

build claude AskUserQuestion .claude/claude.md
build codex request_user_input .codex/AGENTS.md
build opencode question .config/opencode/AGENTS.md
